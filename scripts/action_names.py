"""The Mario action names as a lookup, generated from the copied game header.

Reads the `#define ACT_*` lines of tasfw-core/inc/sm64/Sm64.hpp (the decomp's sm64.h at the
pinned revision, docs/decomp.md) and writes tasfw-scripts/inc/Sm64ActionNames.hpp, a switch
from an action's value to its name, which the stages' CSV rows carry beside the action's hex
(README.md, "The viewer"). Run it after the header moves to another revision; `--check`
regenerates in memory and exits 1 when the committed header differs, which CI runs.

    python scripts/action_names.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tasfw-core" / "inc" / "sm64" / "Sm64.hpp"
TARGET = ROOT / "tasfw-scripts" / "inc" / "Sm64ActionNames.hpp"

DEFINE = re.compile(r"^\s*#define\s+(ACT_[A-Z0-9_]+)\b(.*)$")
VALUE = re.compile(r"0[xX]([0-9A-Fa-f]{1,8})\b")
NOT_ACTIONS = ("ACT_FLAG_", "ACT_GROUP_", "ACT_ID_MASK")


def actions(lines):
    """(name, value) per action define, in the header's order; the masks and flags left out.
    A value may sit on the line after a trailing backslash."""
    found = []
    pending = None
    for line in lines:
        if pending is not None:
            value = VALUE.search(line)
            if value:
                found.append((pending, int(value.group(1), 16)))
            pending = None
            continue
        match = DEFINE.match(line)
        if not match:
            continue
        name, rest = match.group(1), match.group(2)
        if name.startswith(NOT_ACTIONS):
            continue
        value = VALUE.search(rest.split("//")[0])
        if value:
            found.append((name, int(value.group(1), 16)))
        elif rest.rstrip().endswith("\\"):
            pending = name
    return found


def render(found):
    seen = {}
    out = [
        "#pragma once",
        "// Generated by scripts/action_names.py from tasfw-core/inc/sm64/Sm64.hpp (the decomp's",
        "// sm64.h at the pinned revision, docs/decomp.md); do not edit, regenerate. The name of a",
        "// Mario action for its value, \"?\" for one the header does not define; the stages' CSV rows",
        "// carry it beside the action's hex (README.md, \"The viewer\").",
        "#include <cstdint>",
        "",
        "inline const char* Sm64ActionName(uint32_t action)",
        "{",
        "\tswitch (action)",
        "\t{",
    ]
    for name, value in found:
        if value in seen:
            out.append("\t// 0x%08X is %s too (%s above)" % (value, name, seen[value]))
            continue
        seen[value] = name
        out.append("\tcase 0x%08X: return \"%s\";" % (value, name))
    out += ["\tdefault: return \"?\";", "\t}", "}", ""]
    return "\n".join(out)


def main(argv):
    check = "--check" in argv
    found = actions(SOURCE.read_text(encoding="utf-8").splitlines())
    if len(found) < 100:
        sys.exit("only %d action defines found in %s; the header's layout changed" % (len(found), SOURCE))
    text = render(found)
    if check:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current != text:
            sys.exit("%s is stale: run scripts/action_names.py" % TARGET)
        print("%s: current (%d actions)" % (TARGET.relative_to(ROOT), len(found)))
        return 0
    with open(TARGET, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d actions)" % (TARGET.relative_to(ROOT), len(found)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
